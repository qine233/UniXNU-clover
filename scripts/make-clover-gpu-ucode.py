#!/usr/bin/env python3
"""Turn a5xx microcode blobs into a C file drivers/CloverGpu links.

Why embed instead of a payload data object: the driver's first job is to prove the CP can be started,
and a data-object reader is a second subsystem that would have to be right before the first can be
tested. An embedded blob is one array, one size, and the same bytes every boot; the object path can
come later for size.

Usage:
    scripts/make-clover-gpu-ucode.py --pfp a530_pfp.fw --pm4 a530_pm4.fw -o drivers/CloverGpu/ucode_a530.c

The output defines the two arrays the driver declares, plus their sizes and the sha256 of each input so
the generated file says what it was made from.
"""
import argparse
import hashlib
import pathlib


def emit(name, data):
    lines = [f'const unsigned char {name}[] = {{']
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        lines.append('    ' + ','.join(f'0x{b:02x}' for b in chunk) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--pfp', required=True, type=pathlib.Path)
    ap.add_argument('--pm4', required=True, type=pathlib.Path)
    ap.add_argument('-o', '--output', required=True, type=pathlib.Path)
    args = ap.parse_args()

    pfp = args.pfp.read_bytes()
    pm4 = args.pm4.read_bytes()
    if len(pfp) <= 4 or len(pm4) <= 4:
        raise SystemExit('a microcode blob needs more than its skipped date word')
    out = []
    out.append('// Generated by scripts/make-clover-gpu-ucode.py -- do not edit.')
    out.append(f'// pfp: {args.pfp.name} {len(pfp)} bytes sha256 {hashlib.sha256(pfp).hexdigest()}')
    out.append(f'// pm4: {args.pm4.name} {len(pm4)} bytes sha256 {hashlib.sha256(pm4).hexdigest()}')
    out.append('#ifndef CLOVER_GPU_UCODE_A530_H')
    out.append('#define CLOVER_GPU_UCODE_A530_H')
    out.append('#include <stddef.h>')
    out.append('')
    out.append(emit('clover_gpu_pfp_blob', pfp).replace('const unsigned char', 'static const unsigned char'))
    out.append('')
    out.append(emit('clover_gpu_pm4_blob', pm4).replace('const unsigned char', 'static const unsigned char'))
    out.append('')
    out.append(f'static const size_t clover_gpu_pfp_size = {len(pfp)};')
    out.append(f'static const size_t clover_gpu_pm4_size = {len(pm4)};')
    out.append('')
    out.append('#endif // CLOVER_GPU_UCODE_A530_H')
    out.append('')
    args.output.write_text('\n'.join(out))
    print(f'wrote {args.output} pfp={len(pfp)} pm4={len(pm4)}')


if __name__ == '__main__':
    main()
